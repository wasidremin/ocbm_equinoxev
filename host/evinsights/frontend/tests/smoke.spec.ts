import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
test('synthetic analytics through the production UI',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.getByLabel('Vehicle ID',{exact:true}).fill('synthetic-equinox');
 await page.getByLabel('Device API key',{exact:true}).fill(process.env.EVINSIGHTS_TEST_KEY||'');
 await page.getByRole('button',{name:'Open analytics'}).click();
 await expect(page.getByText('SYNTHETIC DEMONSTRATION',{exact:false})).toBeVisible();
 await page.getByRole('button',{name:'Explore',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Explore conditions & efficiency'})).toBeVisible();
 await page.locator('.recent button').first().click();
 await expect(page.getByRole('heading',{name:'Raw sample browser'})).toBeVisible();
 await expect(page.getByRole('heading',{name:'State transitions'}).locator('xpath=following-sibling::pre[1]')).toContainText('COMPLETING');
 await page.getByRole('button',{name:'Charging',exact:true}).click();
 await page.locator('.recent button').first().click();
 await expect(page.getByRole('heading',{name:'Charging power curve · W'})).toBeVisible();
 await page.getByRole('button',{name:'Insights',exact:true}).click();
 await page.getByRole('button',{name:'Run & save analysis'}).click();
 await expect(page.getByText('Sample size',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Trips',exact:true}).click();
 await expect(page.locator('.table-row').first()).toBeVisible();
 await page.getByRole('button',{name:'Signals',exact:true}).click();
 await expect(page.getByRole('table',{name:'Received signal evidence'})).toBeVisible();
 await expect(page.getByRole('cell',{name:'LIVE AVAILABLE OBSERVED',exact:true}).first()).toBeVisible();
 await expect(page.getByRole('heading',{name:'Known signals not received in this window'})).toBeVisible();
 await page.getByLabel('Observation window').selectOption('24');
 await expect(page.getByRole('table',{name:'Received signal evidence'})).toBeVisible();
 const [coverageDownload]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Export coverage page'}).click()]);
 expect(coverageDownload.suggestedFilename()).toBe('signal-coverage-page.json');
 const exportPath=await coverageDownload.path();
 expect(exportPath).not.toBeNull();
 const exported=JSON.parse(await readFile(exportPath!,'utf8'));
 expect(exported.vehicle_id).toBe('synthetic-equinox');
 expect(exported.window_hours).toBe(24);
 expect(exported.signals.length).toBeGreaterThan(0);
 expect(exported.caveat).toContain('Not proof of VHAL absence');
 expect(errors).toEqual([]);
});
